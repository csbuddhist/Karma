export function isSessionExpiredError(reason: unknown): boolean {
  const message = reason instanceof Error ? reason.message : String(reason);
  return message === sessionExpiredMessage;
}

export function getInitialLocale(): Locale {
  try {
    const stored = localStorage.getItem(localeStorageKey);
    return stored === "en" || stored === "zh-CN" ? stored : "zh-CN";
  } catch {
    return "zh-CN";
  }
}

export function persistLocale(locale: Locale): void {
  try {
    localStorage.setItem(localeStorageKey, locale);
  } catch {
    // The selection still applies for the current session when storage is unavailable.
  }
}

export function isMessageKey(key: string): key is MessageKey {
  return Object.hasOwn(zh, key);
}

export function createTranslator(locale: Locale): Translate {
  return (key, values) => {
    let message = messages[locale][key];
    if (!values) return message;
    for (const [name, value] of Object.entries(values)) {
      message = message.replaceAll(`{${name}}`, String(value));
    }
    return message;
  };
}

export function localizeError(reason: unknown, t: Translate): string {
  const message = reason instanceof Error ? reason.message : String(reason);
  const key = errorKeys.get(message);
  return key ? t(key) : message;
}
